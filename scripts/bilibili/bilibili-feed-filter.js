function normalize(value) {
    return String(value ?? "")
        .trim()
        .toLowerCase();
}


function prepareList(list) {
    return [
        ...new Set(
            list
                .map(normalize)
                .filter(Boolean)
        )
    ];
}


const KEYWORDS = prepareList(BLOCK_KEYWORDS);
const PEOPLE = prepareList(BLOCK_PEOPLE);
const UP_NAMES = prepareList(BLOCK_UP);


function findHit(text, list) {
    if (!text) {
        return null;
    }

    for (const word of list) {
        if (text.includes(word)) {
            return word;
        }
    }

    return null;
}


// ============================================================
// Feed 类型判断
// ============================================================

function isAd(item) {
    return (
        item?.card_type === "cm_v1" ||
        item?.card_goto === "ad_web_s" ||
        item?.ad_info != null
    );
}


function isLive(item) {
    return (
        item?.goto === "live" ||
        item?.card_goto === "live" ||
        item?.card_type === "live"
    );
}


function isPictureOrArticle(item) {
    return (
        item?.goto === "picture" ||
        item?.card_goto === "picture" ||
        item?.goto === "article" ||
        item?.card_goto === "article"
    );
}


function getDuration(item) {
    const raw =
        item?.player_args?.duration ??
        item?.duration;

    if (raw == null) {
        return null;
    }

    const seconds = Number(raw);

    if (!Number.isFinite(seconds)) {
        return null;
    }

    return seconds;
}


